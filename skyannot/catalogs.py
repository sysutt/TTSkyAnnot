"""Bundled catalogues: OpenNGC (Messier, NGC, IC + addendum, ellipses and nebula outlines), Sharpless,
the Yale Bright Star Catalogue with IAU star names, and Stellarium's nebula outlines (used only where
OpenNGC has no outline). Sources and licences: THIRD_PARTY_NOTICES.md.
"""
from __future__ import annotations

import csv
import functools
import math
import os
import re
import sys
from dataclasses import dataclass, field

import numpy as np


def data_dir() -> str:
    base = getattr(sys, "_MEIPASS", None) or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    return os.path.join(base, "data")


def _sexa(s: str, hours: bool):
    s = (s or "").strip()
    if not s:
        return None
    sign = -1.0 if s.startswith("-") else 1.0
    p = [float(x) for x in s.lstrip("+-").split(":")]
    v = p[0] + (p[1] if len(p) > 1 else 0) / 60.0 + (p[2] if len(p) > 2 else 0) / 3600.0
    return sign * v * (15.0 if hours else 1.0)


def _f(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


@dataclass
class DSO:
    name: str                  # canonical, e.g. "NGC598", "IC1396", "M33", "Sh2-131", "B33"
    ra: float
    dec: float
    type: str = ""
    mag: float | None = None
    maj: float | None = None   # arcmin
    minr: float | None = None  # arcmin
    pa: float | None = None    # degrees, north through east
    common: str = ""
    messier: str = ""          # "M1"
    ngcic: str = ""            # the NGC/IC designation of a Messier object
    pgc: list = field(default_factory=list)


_NGC_RE = re.compile(r"^(NGC|IC)0*(\d+)(.*)$")


def canonical(name: str) -> str:
    """'NGC0598' / 'NGC 598' -> 'NGC598', 'M 42' -> 'M42', 'IC 0434' -> 'IC434', 'SH 2-155' -> 'Sh2-155'."""
    s = re.sub(r"\s+", " ", (name or "").strip())
    m = re.match(r"^(NGC|IC|M|LBN|LDN|B|Ced|VdB|vdB|VDB|RCW|PGC|Mel|Cr|C)\s*0*(\d+)(.*)$", s)
    if m:
        pre = {"VDB": "vdB", "VdB": "vdB"}.get(m.group(1), m.group(1))
        return "%s%s%s" % (pre, m.group(2), m.group(3).strip())
    m = re.match(r"^(SH|Sh)\s*2\s*-\s*0*(\d+)$", s)
    if m:
        return "Sh2-%s" % m.group(2)
    return s


@functools.lru_cache(maxsize=1)
def posang_fix() -> dict:
    """Position angles that fill gaps in OpenNGC, generated by tools/leda_pa.py from HyperLEDA.

    OpenNGC leaves `PosAng` empty for about 3200 entries. A blank is not neutral: drawing an ellipse at 0
    degrees asserts a vertical direction the catalogue never gave, so where HyperLEDA has an adopted angle it
    is used instead. The file is an addendum rather than an edit of NGC.csv, so the upstream catalogue stays
    as published and this can be regenerated or removed without touching it.
    """
    path = os.path.join(data_dir(), "openngc", "posang.csv")
    out = {}
    try:
        with open(path, encoding="utf-8") as f:
            for r in csv.DictReader(f, delimiter=";"):
                name = canonical((r.get("Name") or "").strip())
                value = _f(r.get("PosAng"))
                if name and value is not None:
                    out[name] = value
    except OSError:
        return {}
    return out


@functools.lru_cache(maxsize=1)
def openngc() -> list:
    fix = posang_fix()
    out = []
    for fn in ("NGC.csv", "addendum.csv"):
        with open(os.path.join(data_dir(), "openngc", fn), encoding="utf-8") as f:
            for r in csv.DictReader(f, delimiter=";"):
                if r["Type"] in ("Dup", "NonEx"):
                    continue
                ra, dec = _sexa(r["RA"], True), _sexa(r["Dec"], False)
                if ra is None or dec is None:
                    continue
                name = canonical(r["Name"])
                ids = [x.strip() for x in (r["Identifiers"] or "").split(",") if x.strip()]
                pgc = ["PGC%d" % int(x.split()[1]) for x in ids if x.startswith("PGC ") and x.split()[1].isdigit()]
                m = r["M"].strip()
                out.append(DSO(
                    name=name, ra=ra, dec=dec, type=r["Type"],
                    mag=_f(r["V-Mag"]) if _f(r["V-Mag"]) is not None else _f(r["B-Mag"]),
                    maj=_f(r["MajAx"]), minr=_f(r["MinAx"]),
                    pa=_f(r["PosAng"]) if _f(r["PosAng"]) is not None else fix.get(name),
                    common=(r["Common names"] or "").split(",")[0].strip(),
                    messier=("M%d" % int(m)) if m.isdigit() else "",
                    ngcic=name if name.startswith(("NGC", "IC")) else "",
                    pgc=pgc))
    return out


def messier() -> list:
    rows = []
    for d in openngc():
        if d.messier:
            rows.append(d)
        elif re.match(r"^M\d+$", d.name):             # Messier objects with no NGC number (addendum)
            d.messier = d.name
            rows.append(d)
    seen, out = set(), []
    for d in sorted(rows, key=lambda d: int(d.messier[1:])):
        if d.messier not in seen:
            seen.add(d.messier)
            out.append(d)
    return out


def ngcic() -> list:
    return [d for d in openngc() if d.name.startswith(("NGC", "IC"))]


def others() -> list:
    """Addendum objects that are neither NGC/IC nor Messier (Barnard, Caldwell, Melotte, ...): preview only."""
    return [d for d in openngc() if not d.name.startswith(("NGC", "IC")) and not d.messier]


@functools.lru_cache(maxsize=1)
def searchable() -> list:
    """(searchable text, object) for everything the object-name field can complete from.

    The text holds every name an object is known by — designation, Messier number, NGC/IC number, common
    name, and the bare catalogue number — so "ring", "m57", "ngc6720" and "6720" all find the Ring Nebula.
    Ordered brightest Messier first, so a one-letter search offers the famous objects rather than NGC 1.
    """
    entries = []
    for d in openngc() + sharpless():
        keys = {d.name.lower().replace(" ", "")}
        num = re.sub(r"^(ngc|ic|sh2-|sh2)", "", d.name.lower().replace(" ", ""))
        if num:
            keys.add(num)
        if d.messier:
            keys.add(d.messier.lower())
        if d.ngcic:
            keys.add(d.ngcic.lower())
        if d.common:
            keys.add(d.common.lower())
        entries.append((0 if d.messier else 1, d.mag if d.mag is not None else 99.0, "|".join(sorted(keys)), d))
    entries.sort(key=lambda e: (e[0], e[1], e[3].name))
    return [(e[2], e[3]) for e in entries]


def find_objects(text: str, limit: int = 40) -> list:
    """Objects matching `text` by designation, catalogue number or common name, best first.

    An exact name wins, then a name that starts with the text, then anything containing it; brighter first
    within each group.
    """
    q = " ".join((text or "").lower().split()).replace(" ", "")
    if not q:
        return []
    exact, starts, contains = [], [], []
    for keys, d in searchable():
        names = keys.split("|")
        if q in names:
            exact.append(d)
        elif any(n.startswith(q) for n in names):
            starts.append(d)
        elif any(q in n for n in names):
            contains.append(d)
    return (exact + starts + contains)[:limit]


def label_for(d) -> str:
    """How an object is shown in the object-name field: the name the user would recognise it by."""
    if d.messier and d.ngcic and d.messier != d.ngcic:
        base = "%s (%s)" % (d.messier, d.ngcic)
    else:
        base = d.messier or d.name
    return "%s%s" % (base, " · %s" % d.common if d.common else "")


@functools.lru_cache(maxsize=1)
def sharpless() -> list:
    out = []
    with open(os.path.join(data_dir(), "vizier", "sharpless_VII20.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            out.append(DSO(name="Sh2-%s" % r["Sh2"], ra=float(r["_RAJ2000"]), dec=float(r["_DEJ2000"]),
                           type="HII", maj=_f(r["Diam"]), minr=_f(r["Diam"]), pa=0.0))
    return out


# ───────────────────────────── named stars ─────────────────────────────
_GREEK = {"Alp": "alf", "Bet": "bet", "Gam": "gam", "Del": "del", "Eps": "eps", "Zet": "zet", "Eta": "eta",
          "The": "the", "Iot": "iot", "Kap": "kap", "Lam": "lam", "Mu": "mu.", "Nu": "nu.", "Xi": "ksi",
          "Omi": "omi", "Pi": "pi.", "Rho": "rho", "Sig": "sig", "Tau": "tau", "Ups": "ups", "Phi": "phi",
          "Chi": "chi", "Psi": "psi", "Ome": "ome"}
_BSC_NAME = re.compile(r"^\s*(\d+)?\s*([A-Z][a-z]{1,2})?(\d)?\s*([A-Z][A-Za-z]{2})\s*$")


def _designation(bsc_name: str) -> str | None:
    """Yale BSC 'Name' -> PixInsight-style designation: '21Alp And' -> 'alf And', 'Mu  Cep' -> 'mu. Cep',
    'Kap1Scl' -> 'kap1 Scl', '33    Psc' -> '33 Psc'."""
    m = _BSC_NAME.match(bsc_name or "")
    if not m:
        return None
    flam, bayer, sup, con = m.groups()
    if bayer and bayer in _GREEK:
        return "%s%s %s" % (_GREEK[bayer], sup or "", con)
    if flam:
        return "%s %s" % (flam, con)
    return None


@functools.lru_cache(maxsize=1)
def iau_names() -> dict:
    """HD number -> (IAU name, HIP number) from the WGSN list."""
    tail = re.compile(r"(\S+)\s+(-?[\d.]+|_)\s+(\S+)\s+(\d+|_)\s+(\d+|_)\s+([\d.]+)\s+(-?[\d.]+)\s+(\d{4}-\d{2}-\d{2})")
    out = {}
    with open(os.path.join(data_dir(), "iau", "IAU-CSN.txt"), encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line[0] in "#$":
                continue
            m = None
            for m in tail.finditer(line):
                pass
            if not m:
                continue
            hip, hd = m.group(4), m.group(5)
            if hd.isdigit():
                out[int(hd)] = (line.split()[0], int(hip) if hip.isdigit() else None)
    return out


@dataclass
class NamedStar:
    name: str
    ra: float
    dec: float
    mag: float | None
    sptype: str
    common: str
    hd: int | None
    hip: int | None = None


@functools.lru_cache(maxsize=1)
def named_stars() -> list:
    names = iau_names()
    out = []
    with open(os.path.join(data_dir(), "vizier", "bsc5_V50.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            des = _designation(r["Name"])
            if not des or not r["RAJ2000"]:
                continue
            ra = _sexa(r["RAJ2000"].replace(" ", ":"), True)
            dec = _sexa(r["DEJ2000"].replace(" ", ":"), False)
            hd = int(r["HD"]) if r["HD"].strip().isdigit() else None
            common, hip = names.get(hd, ("", None)) if hd else ("", None)
            out.append(NamedStar(des, ra, dec, _f(r["Vmag"]), (r["SpType"] or "").strip(), common, hd, hip))
    return out


# ───────────────────────────── outlines ─────────────────────────────
def _read_outlines(path: str, source: str) -> list:
    """Stellarium outline format: 'RA_hours Dec_deg start|vertex|end [name]'. Returns [(name, source, [(ra, dec)])]."""
    polys, cur, name = [], None, ""
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            parts = line.split()
            if len(parts) < 3 or line.lstrip().startswith("#"):
                continue
            try:
                ra, dec = float(parts[0]) * 15.0, float(parts[1])
            except ValueError:
                continue
            kind = parts[2]
            if kind == "start":
                name = canonical(" ".join(parts[3:]))
                cur = [(ra, dec)]
            elif kind == "vertex" and cur is not None:
                cur.append((ra, dec))
            elif kind == "end" and cur is not None:
                cur.append((ra, dec))
                polys.append((name, source, cur))
                cur = None
    return polys


def _inside(p, q):
    """Fraction of the vertices of polygon p (n x 2) that lie inside polygon q (ray casting)."""
    x, y = p[:, 0][:, None], p[:, 1][:, None]
    x0, y0 = q[:, 0][None, :], q[:, 1][None, :]
    x1, y1 = np.roll(q[:, 0], -1)[None, :], np.roll(q[:, 1], -1)[None, :]
    with np.errstate(divide="ignore", invalid="ignore"):
        cross = ((y0 > y) != (y1 > y)) & (x < (x1 - x0) * (y - y0) / (y1 - y0) + x0)
    return float(np.mean(cross.sum(axis=1) % 2 == 1))


def _outermost(polys: list) -> list:
    """OpenNGC traces up to three brightness levels of a nebula as nested contours (M20: three rings). One
    outline per object is enough on a picture: keep the contours that do not lie inside a larger contour of
    the same object (separate pieces of the outer level all stay)."""
    groups: dict = {}
    for i, (name, src, _pts) in enumerate(polys):
        groups.setdefault((name, src), []).append(i)
    keep = set()
    for idx in groups.values():
        if len(idx) == 1:
            keep.update(idx)
            continue
        ra0, de0 = polys[idx[0]][2][0]
        c = math.cos(math.radians(de0))
        xy = {i: np.array([(((ra - ra0 + 180.0) % 360.0 - 180.0) * c, de - de0) for ra, de in polys[i][2]])
              for i in idx}
        area = {i: abs(float(np.dot(p[:, 0], np.roll(p[:, 1], -1)) - np.dot(p[:, 1], np.roll(p[:, 0], -1)))) / 2
                for i, p in xy.items()}
        for i in idx:
            if not any(j != i and area[j] > area[i] and _inside(xy[i], xy[j]) >= 0.8 for j in idx):
                keep.add(i)
    return [p for i, p in enumerate(polys) if i in keep]


@functools.lru_cache(maxsize=1)
def outlines() -> list:
    """OpenNGC outlines first; Stellarium outlines only for objects OpenNGC does not outline (names are
    compared after mapping Messier numbers to their NGC/IC designation, so 'M42' and 'NGC1976' match).
    Only the outermost contour of each object is kept."""
    d = data_dir()
    onc = _outermost(_read_outlines(os.path.join(d, "openngc", "outlines_stellarium.dat"), "OpenNGC"))
    stel = _outermost(_read_outlines(os.path.join(d, "stellarium", "outlines.dat"), "Stellarium"))
    m2n = {o.messier: o.name for o in messier() if o.ngcic}
    covered = {m2n.get(n, n) for n, _, _ in onc}
    return onc + [p for p in stel if m2n.get(p[0], p[0]) not in covered]
